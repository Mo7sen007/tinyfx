//! # glue
//!
//! Generate the `tinyfx.gen.ts` runtime glue file.
//!
//! ## Responsibilities
//! - Emit imports for dynamic components and page modules
//! - Build the route registry used by the runtime router
//! - Generate component bootstrap and remount helpers
//!
//! ## What this module does NOT do
//! - It does not scan the filesystem for components or pages
//! - It does not compile component HTML
//! - It does not orchestrate build phases

use std::collections::HashMap;
use std::path::{Path, PathBuf};

use super::component::CompiledComponent;
use super::pages::PageDef;

/// Generate the `tinyfx.gen.ts` source for the current build.
///
/// The output wires dynamic components to `data-component` markers, page
/// modules to route patterns, and bootstraps the runtime router.
///
/// # Errors
/// This function does not return build errors directly because it only formats
/// a source string. Invalid output paths or missing files are handled by later
/// file-writing and bundling stages.
pub fn generate_registry(
    component_registry: &HashMap<String, CompiledComponent>,
    pages: &[PageDef],
) -> String {
    let mut component_imports = Vec::new();
    let mut component_entries = Vec::new();
    let mut page_imports = Vec::new();
    let mut page_entries = Vec::new();

    let src_dir = infer_src_dir(component_registry, pages);

    let mut components: Vec<&CompiledComponent> = component_registry.values().collect();
    components.sort_by(|left, right| left.name.cmp(&right.name));

    for component in components {
        if !component.is_dynamic {
            continue;
        }

        let script_path = component.path.with_extension("ts");
        if script_path.exists() {
            let import_path = relative_import(&src_dir, &script_path.with_extension(""));
            let alias = format!("{}Module", component.name);
            component_imports.push(format!("import * as {} from \"{}\";", alias, import_path));
            component_entries.push(format!(
                "  \"{}\": (el, ctx) => mountComponent({}, el, ctx),",
                component.name, alias
            ));
        }
    }

    let mut sorted_pages = pages.to_vec();
    sorted_pages.sort_by(|left, right| left.route.cmp(&right.route));

    for (index, page) in sorted_pages.iter().enumerate() {
        let script_path = page.source_path.with_extension("ts");
        if script_path.exists() {
            let import_path = relative_import(&src_dir, &script_path.with_extension(""));
            let alias = format!("PageModule{}", index);
            page_imports.push(format!("import * as {} from \"{}\";", alias, import_path));
            page_entries.push(format!("  \"{}\": {},", page.route, alias));
        }
    }

    let mut out = String::new();
    out.push_str("// Auto-generated by tinyfx build — do not edit.\n");
    out.push_str("// This file wires component mount() factories to data-component attributes.\n\n");
    out.push_str("import { initRouter, navigate } from \"@tinyfx/runtime\";\n");
    out.push_str("import type { TinyFxContext } from \"@tinyfx/runtime\";\n\n");
    out.push_str("type ComponentModule = {\n");
    out.push_str("  mount?: (el: HTMLElement, ctx: TinyFxContext) => any;\n");
    out.push_str("  init?: (el: HTMLElement, ctx: TinyFxContext) => void;\n");
    out.push_str("};\n\n");
    out.push_str("type PageModule = {\n");
    out.push_str("  init?: (el: HTMLElement, ctx: TinyFxContext) => void;\n");
    out.push_str("};\n\n");
    out.push_str("function mountComponent(module: ComponentModule, el: HTMLElement, ctx: TinyFxContext) {\n");
    out.push_str("  if (el.dataset.tinyfxMounted === \"true\") return undefined;\n");
    out.push_str("  el.dataset.tinyfxMounted = \"true\";\n");
    out.push_str("  if (typeof module.mount === \"function\") {\n");
    out.push_str("    return module.mount(el, ctx);\n");
    out.push_str("  }\n");
    out.push_str("  if (typeof module.init === \"function\") {\n");
    out.push_str("    module.init(el, ctx);\n");
    out.push_str("  }\n");
    out.push_str("  return undefined;\n");
    out.push_str("}\n\n");

    if component_imports.is_empty() {
        out.push_str("const registry: Record<string, (el: HTMLElement, ctx: TinyFxContext) => any> = {};\n");
    } else {
        for import_stmt in &component_imports {
            out.push_str(import_stmt);
            out.push('\n');
        }
        out.push('\n');
        out.push_str("const registry: Record<string, (el: HTMLElement, ctx: TinyFxContext) => any> = {\n");
        for entry in &component_entries {
            out.push_str(entry);
            out.push('\n');
        }
        out.push_str("};\n");
    }

    out.push('\n');
    for import_stmt in &page_imports {
        out.push_str(import_stmt);
        out.push('\n');
    }
    if !page_imports.is_empty() {
        out.push('\n');
    }

    out.push_str("const routes = {\n");
    for page in &sorted_pages {
        out.push_str(&format!(
            "  \"{}\": {{ page: \"{}\", path: \"{}\" }},\n",
            page.route, page.name, page.route
        ));
    }
    out.push_str("} as const;\n\n");

    if page_entries.is_empty() {
        out.push_str("const pageModules: Record<string, PageModule> = {};\n\n");
    } else {
        out.push_str("const pageModules: Record<string, PageModule> = {\n");
        for entry in &page_entries {
            out.push_str(entry);
            out.push('\n');
        }
        out.push_str("};\n\n");
    }

    out.push_str("function matchesRoute(pattern: string, pathname: string): boolean {\n");
    out.push_str("  const patternParts = pattern.split(\"/\").filter(Boolean);\n");
    out.push_str("  const pathParts = pathname.split(\"/\").filter(Boolean);\n");
    out.push_str("  if (patternParts.length !== pathParts.length) return false;\n");
    out.push_str("  for (let i = 0; i < patternParts.length; i++) {\n");
    out.push_str("    const segment = patternParts[i];\n");
    out.push_str("    if (segment.startsWith(\":\")) continue;\n");
    out.push_str("    if (segment !== pathParts[i]) return false;\n");
    out.push_str("  }\n");
    out.push_str("  return true;\n");
    out.push_str("}\n\n");
    out.push_str("function extractParams(pattern: string, pathname: string): Record<string, string> {\n");
    out.push_str("  const patternParts = pattern.split(\"/\").filter(Boolean);\n");
    out.push_str("  const pathParts = pathname.split(\"/\").filter(Boolean);\n");
    out.push_str("  const params: Record<string, string> = {};\n");
    out.push_str("  for (let i = 0; i < patternParts.length; i++) {\n");
    out.push_str("    const segment = patternParts[i];\n");
    out.push_str("    if (!segment.startsWith(\":\")) continue;\n");
    out.push_str("    const key = segment.slice(1);\n");
    out.push_str("    params[key] = decodeURIComponent(pathParts[i] ?? \"\");\n");
    out.push_str("  }\n");
    out.push_str("  return params;\n");
    out.push_str("}\n\n");
    out.push_str("function createContext(pattern: string): TinyFxContext {\n");
    out.push_str("  return { params: extractParams(pattern, window.location.pathname), navigate };\n");
    out.push_str("}\n\n");
    out.push_str("function resolveCurrentPattern(pathname: string): string | null {\n");
    out.push_str("  for (const pattern of Object.keys(routes)) {\n");
    out.push_str("    if (matchesRoute(pattern, pathname)) return pattern;\n");
    out.push_str("  }\n");
    out.push_str("  return null;\n");
    out.push_str("}\n\n");
    out.push_str("function runPageInit(pattern: string, ctx: TinyFxContext): void {\n");
    out.push_str("  const pathname = window.location.pathname;\n");
    out.push_str("  if (!matchesRoute(pattern, pathname)) return;\n");
    out.push_str("  const mod = pageModules[pattern];\n");
    out.push_str("  if (typeof mod?.init === \"function\") {\n");
    out.push_str("    mod.init(document.body, ctx);\n");
    out.push_str("  }\n");
    out.push_str("}\n\n");
    out.push_str("initRouter(routes);\n\n");
    out.push_str("let bootstrapped = false;\n\n");
    out.push_str("export function bootstrapTinyFx(root: Document | HTMLElement = document) {\n");
    out.push_str("  if (bootstrapped) return [];\n");
    out.push_str("  bootstrapped = true;\n");
    out.push_str("  const pattern = resolveCurrentPattern(window.location.pathname) ?? \"/\";\n");
    out.push_str("  const ctx = createContext(pattern);\n");
    out.push_str("  const instances = setupComponents(ctx, root);\n");
    out.push_str("  runPageInit(pattern, ctx);\n");
    out.push_str("  return instances;\n");
    out.push_str("}\n\n");
    out.push_str("if (typeof document !== \"undefined\") {\n");
    out.push_str("  if (document.readyState === \"loading\") {\n");
    out.push_str("    document.addEventListener(\"DOMContentLoaded\", () => {\n");
    out.push_str("      bootstrapTinyFx();\n");
    out.push_str("    }, { once: true });\n");
    out.push_str("  } else {\n");
    out.push_str("    bootstrapTinyFx();\n");
    out.push_str("  }\n");
    out.push_str("}\n\n");
    out.push_str("export function setupComponents(\n");
    out.push_str("  ctx: TinyFxContext,\n");
    out.push_str("  root: Document | HTMLElement = document,\n");
    out.push_str(") {\n");
    out.push_str("  const instances: any[] = [];\n");
    out.push_str("  root.querySelectorAll(\"[data-component]\").forEach((el) => {\n");
    out.push_str("    const name = el.getAttribute(\"data-component\");\n");
    out.push_str("    if (name && registry[name]) {\n");
    out.push_str("      const inst = registry[name](el as HTMLElement, ctx);\n");
    out.push_str("      if (inst) instances.push(inst);\n");
    out.push_str("    }\n");
    out.push_str("  });\n");
    out.push_str("  return instances;\n");
    out.push_str("}\n");

    out
}

fn infer_src_dir(
    component_registry: &HashMap<String, CompiledComponent>,
    pages: &[PageDef],
) -> PathBuf {
    for component in component_registry.values() {
        if let Some(src_dir) = find_src_ancestor(&component.path) {
            return src_dir;
        }
    }

    for page in pages {
        if let Some(src_dir) = find_src_ancestor(&page.source_path) {
            return src_dir;
        }
    }

    PathBuf::from(".")
}

fn find_src_ancestor(path: &Path) -> Option<PathBuf> {
    for ancestor in path.ancestors() {
        if ancestor.file_name().and_then(|name| name.to_str()) == Some("src") {
            return Some(ancestor.to_path_buf());
        }
    }

    None
}

fn relative_import(from_dir: &Path, target: &Path) -> String {
    let from_parts: Vec<_> = from_dir.components().collect();
    let target_parts: Vec<_> = target.components().collect();

    let mut common = 0;
    while common < from_parts.len()
        && common < target_parts.len()
        && from_parts[common] == target_parts[common]
    {
        common += 1;
    }

    let mut import_path = String::new();
    let ups = from_parts.len().saturating_sub(common);
    if ups == 0 {
        import_path.push_str("./");
    } else {
        for _ in 0..ups {
            import_path.push_str("../");
        }
    }

    for (index, part) in target_parts[common..].iter().enumerate() {
        if index > 0 {
            import_path.push('/');
        }
        import_path.push_str(&part.as_os_str().to_string_lossy());
    }

    import_path
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn empty_registry() {
        let result = generate_registry(&HashMap::new(), &[]);
        assert!(result.contains("const registry"));
        assert!(result.contains("setupComponents"));
        assert!(result.contains("bootstrapTinyFx"));
        assert!(result.contains("createContext"));
        assert!(result.contains("import type { TinyFxContext }"));
        assert!(!result.contains("import * as"));
        assert!(result.contains("initRouter"));
    }

    #[test]
    fn relative_import_same_parent() {
        let result = relative_import(Path::new("src"), Path::new("src/components/Button/Button"));
        assert_eq!(result, "./components/Button/Button");
    }

    #[test]
    fn relative_import_sibling() {
        let result = relative_import(
            Path::new("src/lib"),
            Path::new("src/components/Button/Button"),
        );
        assert_eq!(result, "../components/Button/Button");
    }
}
