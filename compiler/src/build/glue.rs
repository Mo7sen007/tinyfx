use std::collections::HashSet;
use std::path::Path;

/// Generate tinyfx.gen.ts — the component init registry.
///
/// For each used component that has a .ts file with an init() export,
/// emit an import and wire it into initComponents().
pub fn generate_registry(used: &HashSet<String>, components_dir: &Path) -> String {
    let mut imports = Vec::new();
    let mut entries = Vec::new();

    let mut names: Vec<&String> = used.iter().collect();
    names.sort(); // deterministic output

    for name in &names {
        let ts_path = components_dir.join(name.as_str()).join(format!("{}.ts", name));
        if ts_path.exists() {
            let import_path = format!(
                "../{}/{}/{}",
                components_dir.display(),
                name,
                name
            );
            let alias = format!("{}Init", name);
            imports.push(format!(
                "import {{ init as {} }} from \"{}\";",
                alias, import_path
            ));
            entries.push(format!("  \"{}\": {},", name, alias));
        }
    }

    let mut out = String::new();

    out.push_str("// Auto-generated by tinyfx build — do not edit.\n");
    out.push_str("// This file wires component init() functions to data-component attributes.\n");
    out.push('\n');

    if imports.is_empty() {
        // No components have behavior — emit a no-op registry
        out.push_str("const registry: Record<string, (el: HTMLElement) => void> = {};\n");
    } else {
        for imp in &imports {
            out.push_str(imp);
            out.push('\n');
        }
        out.push('\n');
        out.push_str("const registry: Record<string, (el: HTMLElement) => void> = {\n");
        for entry in &entries {
            out.push_str(entry);
            out.push('\n');
        }
        out.push_str("};\n");
    }

    out.push('\n');
    out.push_str("export function initComponents(root: Document | HTMLElement = document) {\n");
    out.push_str("  root.querySelectorAll(\"[data-component]\").forEach((el) => {\n");
    out.push_str("    const name = el.getAttribute(\"data-component\");\n");
    out.push_str("    if (name && registry[name]) {\n");
    out.push_str("      registry[name](el as HTMLElement);\n");
    out.push_str("    }\n");
    out.push_str("  });\n");
    out.push_str("}\n");

    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn empty_registry() {
        let used = HashSet::new();
        let result = generate_registry(&used, Path::new("frontend/components"));
        assert!(result.contains("const registry"));
        assert!(result.contains("initComponents"));
        assert!(!result.contains("import"));
    }
}
