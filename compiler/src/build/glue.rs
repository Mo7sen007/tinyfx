//! # glue
//!
//! Generate the `tinyfx.gen.ts` runtime glue file.
//!
//! ## Responsibilities
//! - Emit imports for dynamic components and page modules
//! - Build the route registry used by the runtime router
//! - Generate component bootstrap and remount helpers
//!
//! ## What this module does NOT do
//! - It does not scan the filesystem for components or pages
//! - It does not compile component HTML
//! - It does not orchestrate build phases

use std::collections::HashMap;
use std::path::{Path, PathBuf};

use super::codegen::{DirectiveContext, TsBuffer};
use super::component::CompiledComponent;
use super::conditional_codegen::{generate_if_helpers, generate_if_wiring};
use super::each_codegen::{generate_each_helpers, generate_each_wiring};
use super::pages::{ComponentDirectives, PageDef, PageDirectives};
use super::wrapper::{self, ComponentWrapperSpec};

#[derive(Debug, Clone)]
struct DynamicComponentImport {
    alias: String,
    import_path: String,
}

/// Generate the `tinyfx.gen.ts` source for the current build.
pub fn generate_registry(
    component_registry: &HashMap<String, CompiledComponent>,
    pages: &[PageDef],
    page_directives: &[PageDirectives],
    component_directives: &[ComponentDirectives],
) -> String {
    let src_dir = infer_src_dir(component_registry, pages);
    let component_imports = collect_dynamic_component_imports(component_registry, &src_dir);
    let sorted_pages = sorted_pages(pages);
    let (page_imports, page_entries, page_module_aliases) =
        collect_page_modules(&src_dir, &sorted_pages);
    let has_each = has_each_sites(page_directives, component_directives);
    let has_dynamic_components = component_registry.values().any(|c| c.is_dynamic);
    let has_instance_tracking = has_each || has_dynamic_components;
    let uses_reactivity = uses_reactivity(page_directives, component_directives);

    let mut buf = TsBuffer::new();
    emit_header(&mut buf);
    emit_runtime_imports(&mut buf, uses_reactivity);
    emit_types(&mut buf);
    if has_instance_tracking {
        emit_each_runtime_helpers(&mut buf);
    }
    emit_mount_component_helper(has_instance_tracking, &mut buf);
    emit_component_imports(&component_imports, &mut buf);
    emit_component_directive_helpers(component_directives, &mut buf);
    emit_registry(component_registry, component_directives, &mut buf);
    emit_page_imports(&page_imports, &mut buf);
    emit_routes(&sorted_pages, &mut buf);
    emit_page_modules(&page_entries, &mut buf);
    emit_page_directive_helpers(page_directives, &page_module_aliases, &mut buf);
    emit_setup_directives(page_directives, &page_module_aliases, &mut buf);
    emit_bootstrap(&mut buf, uses_reactivity);

    buf.build()
}

fn emit_header(buf: &mut TsBuffer) {
    buf.line("// Auto-generated by tinyfx build - do not edit.");
    buf.line("// This file wires component mount() factories to data-component attributes.");
    buf.blank();
}

fn emit_runtime_imports(buf: &mut TsBuffer, uses_reactivity: bool) {
    buf.line("import {");
    buf.indent();
    buf.line("init,");
    buf.line("registerComponent,");
    buf.line("registerPage,");
    buf.line("markMounted,");
    buf.line("navigate,");
    if uses_reactivity {
        buf.line("effect,");
    }
    buf.dedent();
    buf.line("} from \"@tinyfx/runtime\";");
    buf.line("import type { TinyFxContext, RouteDef } from \"@tinyfx/runtime\";");
    buf.blank();
}

fn emit_types(buf: &mut TsBuffer) {
    buf.line("type ComponentModule = {");
    buf.indent();
    buf.line("mount?: (el: HTMLElement, ctx: TinyFxContext) => any;");
    buf.line("init?: (el: HTMLElement, ctx: TinyFxContext) => void;");
    buf.dedent();
    buf.line("};");
    buf.blank();
    buf.line("type PageModule = {");
    buf.indent();
    buf.line("init?: (el: HTMLElement, ctx: TinyFxContext) => void;");
    buf.dedent();
    buf.line("};");
    buf.blank();
}

fn emit_each_runtime_helpers(buf: &mut TsBuffer) {
    buf.line("const __componentInstances = new WeakMap<HTMLElement, { destroy?: () => void }>();");
    buf.blank();
    buf.line(
        "function __registerInstance(el: HTMLElement, instance: { destroy?: () => void }): void {",
    );
    buf.indent();
    buf.line("__componentInstances.set(el, instance);");
    buf.dedent();
    buf.line("}");
    buf.blank();
    buf.line("function __destroyNode(el: HTMLElement): void {");
    buf.indent();
    buf.line("const inst = __componentInstances.get(el);");
    buf.line("inst?.destroy?.();");
    buf.line("__componentInstances.delete(el);");
    buf.line("el.querySelectorAll(\"[data-component]\").forEach((child) => {");
    buf.indent();
    buf.line("const childEl = child as HTMLElement;");
    buf.line("const childInst = __componentInstances.get(childEl);");
    buf.line("childInst?.destroy?.();");
    buf.line("__componentInstances.delete(childEl);");
    buf.dedent();
    buf.line("});");
    buf.dedent();
    buf.line("}");
    buf.blank();
}

fn emit_mount_component_helper(has_instance_tracking: bool, buf: &mut TsBuffer) {
    buf.line(
        "function mountComponent(module: ComponentModule, el: HTMLElement, ctx: TinyFxContext) {",
    );
    buf.indent();
    buf.line("if (!markMounted(el)) return undefined;");
    buf.line("if (typeof module.mount === \"function\") {");
    buf.indent();
    buf.line("const inst = module.mount(el, ctx);");
    if has_instance_tracking {
        buf.line("if (inst && typeof inst === \"object\") {");
        buf.indent();
        buf.line("__registerInstance(el, inst as { destroy?: () => void });");
        buf.dedent();
        buf.line("}");
    }
    buf.line("return inst;");
    buf.dedent();
    buf.line("}");
    buf.line("if (typeof module.init === \"function\") {");
    buf.indent();
    buf.line("module.init(el, ctx);");
    buf.dedent();
    buf.line("}");
    buf.line("return undefined;");
    buf.dedent();
    buf.line("}");
    buf.blank();
}

fn emit_component_imports(imports: &[DynamicComponentImport], buf: &mut TsBuffer) {
    for item in imports {
        buf.line(&format!(
            "import * as {} from \"{}\";",
            item.alias, item.import_path
        ));
    }
    if !imports.is_empty() {
        buf.blank();
    }
}

fn emit_component_directive_helpers(directives: &[ComponentDirectives], buf: &mut TsBuffer) {
    let mut each_sites: Vec<_> = directives
        .iter()
        .flat_map(|directive| directive.each_sites.iter())
        .collect();
    each_sites.sort_by(|left, right| left.id.cmp(&right.id));

    let mut if_sites: Vec<_> = directives
        .iter()
        .flat_map(|directive| directive.if_sites.iter())
        .collect();
    if_sites.sort_by(|left, right| left.id.cmp(&right.id));

    for site in each_sites {
        generate_each_helpers(site, &DirectiveContext::Component, buf);
    }
    for site in if_sites {
        generate_if_helpers(site, &DirectiveContext::Component, buf);
    }
}

fn emit_registry(
    component_registry: &HashMap<String, CompiledComponent>,
    component_directives: &[ComponentDirectives],
    buf: &mut TsBuffer,
) {
    let directives_map: HashMap<&str, &ComponentDirectives> = component_directives
        .iter()
        .map(|directive| (directive.component_name.as_str(), directive))
        .collect();

    let mut components: Vec<&CompiledComponent> = component_registry
        .values()
        .filter(|component| component.is_dynamic)
        .collect();
    components.sort_by(|left, right| left.name.cmp(&right.name));

    for component in &components {
        let spec = ComponentWrapperSpec {
            name: component.name.clone(),
            each_sites: directives_map
                .get(component.name.as_str())
                .map(|directive| directive.each_sites.clone())
                .unwrap_or_default(),
            if_sites: directives_map
                .get(component.name.as_str())
                .map(|directive| directive.if_sites.clone())
                .unwrap_or_default(),
        };
        wrapper::generate_component_wrapper(&spec, buf);
    }

    for component in &components {
        buf.line(&format!(
            "registerComponent(\"{}\", (el, ctx) => __mount_{}(el, ctx));",
            component.name, component.name
        ));
    }
    if !components.is_empty() {
        buf.blank();
    }
}

fn emit_page_imports(imports: &[String], buf: &mut TsBuffer) {
    for item in imports {
        buf.line(item);
    }
    if !imports.is_empty() {
        buf.blank();
    }
}

fn emit_routes(pages: &[PageDef], buf: &mut TsBuffer) {
    buf.line("const routes: Record<string, RouteDef> = {");
    buf.indent();
    for page in pages {
        let (static_segments, param_names) = parse_route_pattern(&page.route);
        buf.line(&format!(
            "\"{}\": {{ staticSegments: [{}], paramNames: [{}] }},",
            page.route, static_segments, param_names
        ));
    }
    buf.dedent();
    buf.line("};");
    buf.blank();
}

fn parse_route_pattern(route: &str) -> (String, String) {
    let segments: Vec<&str> = route.split('/').filter(|s| !s.is_empty()).collect();
    let mut static_parts = Vec::new();
    let mut param_names = Vec::new();

    for seg in segments {
        if seg.starts_with(':') {
            static_parts.push("null".to_string());
            param_names.push(format!("\"{}\"", &seg[1..]));
        } else {
            static_parts.push(format!("\"{}\"", seg));
        }
    }

    (static_parts.join(", "), param_names.join(", "))
}

fn emit_page_modules(entries: &[(String, String)], buf: &mut TsBuffer) {
    if entries.is_empty() {
        return;
    }

    for (route, alias) in entries {
        buf.line(&format!("registerPage(\"{}\", {});", route, alias));
    }
    buf.blank();
}

fn emit_page_directive_helpers(
    directives: &[PageDirectives],
    page_module_aliases: &HashMap<String, String>,
    buf: &mut TsBuffer,
) {
    let mut each_sites = Vec::new();
    let mut if_sites = Vec::new();

    for page in directives {
        let alias = page_module_aliases
            .get(&page.page_name)
            .cloned()
            .unwrap_or_default();
        for site in &page.each_sites {
            each_sites.push((site, alias.clone()));
        }
        for site in &page.if_sites {
            if_sites.push((site, alias.clone()));
        }
    }

    each_sites.sort_by(|(left, _), (right, _)| left.id.cmp(&right.id));
    if_sites.sort_by(|(left, _), (right, _)| left.id.cmp(&right.id));

    for (site, alias) in each_sites {
        generate_each_helpers(
            site,
            &DirectiveContext::Page {
                module_alias: alias,
            },
            buf,
        );
    }
    for (site, alias) in if_sites {
        generate_if_helpers(
            site,
            &DirectiveContext::Page {
                module_alias: alias,
            },
            buf,
        );
    }
}

fn emit_setup_directives(
    directives: &[PageDirectives],
    page_module_aliases: &HashMap<String, String>,
    buf: &mut TsBuffer,
) {
    let mut each_sites = Vec::new();
    let mut if_sites = Vec::new();

    for page in directives {
        let alias = page_module_aliases
            .get(&page.page_name)
            .cloned()
            .unwrap_or_default();
        for site in &page.each_sites {
            each_sites.push((site, alias.clone()));
        }
        for site in &page.if_sites {
            if_sites.push((site, alias.clone()));
        }
    }

    each_sites.sort_by(|(left, _), (right, _)| left.id.cmp(&right.id));
    if_sites.sort_by(|(left, _), (right, _)| left.id.cmp(&right.id));

    buf.line("function setupDirectives(ctx: TinyFxContext): void {");
    buf.indent();
    for (site, alias) in each_sites {
        generate_each_wiring(
            site,
            &DirectiveContext::Page {
                module_alias: alias,
            },
            buf,
        );
    }
    for (site, alias) in if_sites {
        generate_if_wiring(
            site,
            &DirectiveContext::Page {
                module_alias: alias,
            },
            buf,
        );
    }
    buf.dedent();
    buf.line("}");
    buf.blank();
}

fn emit_bootstrap(buf: &mut TsBuffer, _uses_reactivity: bool) {
    buf.line("if (typeof document !== \"undefined\") {");
    buf.indent();
    buf.line("if (document.readyState === \"loading\") {");
    buf.indent();
    buf.line("document.addEventListener(\"DOMContentLoaded\", () => init({ routes, setupDirectives }), { once: true });");
    buf.dedent();
    buf.line("} else {");
    buf.indent();
    buf.line("init({ routes, setupDirectives });");
    buf.dedent();
    buf.line("}");
    buf.dedent();
    buf.line("}");
    buf.blank();
}

fn collect_dynamic_component_imports(
    component_registry: &HashMap<String, CompiledComponent>,
    src_dir: &Path,
) -> Vec<DynamicComponentImport> {
    let mut components: Vec<&CompiledComponent> = component_registry
        .values()
        .filter(|component| component.is_dynamic)
        .collect();
    components.sort_by(|left, right| left.name.cmp(&right.name));

    let mut out = Vec::new();
    for component in components {
        let script_path = component.path.with_extension("ts");
        if script_path.exists() {
            out.push(DynamicComponentImport {
                alias: format!("{}Module", component.name),
                import_path: relative_import(src_dir, &script_path.with_extension("")),
            });
        }
    }

    out
}

fn sorted_pages(pages: &[PageDef]) -> Vec<PageDef> {
    let mut out = pages.to_vec();
    out.sort_by(|left, right| left.route.cmp(&right.route));
    out
}

fn collect_page_modules(
    src_dir: &Path,
    pages: &[PageDef],
) -> (Vec<String>, Vec<(String, String)>, HashMap<String, String>) {
    let mut imports = Vec::new();
    let mut entries = Vec::new();
    let mut aliases = HashMap::new();

    for (index, page) in pages.iter().enumerate() {
        let script_path = page.source_path.with_extension("ts");
        if script_path.exists() {
            let alias = format!("PageModule{}", index);
            imports.push(format!(
                "import * as {} from \"{}\";",
                alias,
                relative_import(src_dir, &script_path.with_extension(""))
            ));
            entries.push((page.route.clone(), alias.clone()));
            aliases.insert(page.name.clone(), alias);
        }
    }

    (imports, entries, aliases)
}

fn has_each_sites(
    page_directives: &[PageDirectives],
    component_directives: &[ComponentDirectives],
) -> bool {
    page_directives
        .iter()
        .any(|directive| !directive.each_sites.is_empty())
        || component_directives
            .iter()
            .any(|directive| !directive.each_sites.is_empty())
}

fn uses_reactivity(
    page_directives: &[PageDirectives],
    component_directives: &[ComponentDirectives],
) -> bool {
    let has_signal_each = page_directives.iter().any(|d| {
        d.each_sites
            .iter()
            .any(|site| matches!(site.source, super::codegen::LoopSource::Signal(_)))
    }) || component_directives.iter().any(|d| {
        d.each_sites
            .iter()
            .any(|site| matches!(site.source, super::codegen::LoopSource::Signal(_)))
    });

    let has_signal_if = page_directives.iter().any(|d| {
        d.if_sites
            .iter()
            .any(|site| site.branches.iter().any(|branch| branch.is_signal))
    }) || component_directives.iter().any(|d| {
        d.if_sites
            .iter()
            .any(|site| site.branches.iter().any(|branch| branch.is_signal))
    });

    has_signal_each || has_signal_if
}

fn infer_src_dir(
    component_registry: &HashMap<String, CompiledComponent>,
    pages: &[PageDef],
) -> PathBuf {
    for component in component_registry.values() {
        if let Some(src_dir) = find_src_ancestor(&component.path) {
            return src_dir;
        }
    }

    for page in pages {
        if let Some(src_dir) = find_src_ancestor(&page.source_path) {
            return src_dir;
        }
    }

    PathBuf::from(".")
}

fn find_src_ancestor(path: &Path) -> Option<PathBuf> {
    for ancestor in path.ancestors() {
        if ancestor.file_name().and_then(|name| name.to_str()) == Some("src") {
            return Some(ancestor.to_path_buf());
        }
    }

    None
}

fn relative_import(from_dir: &Path, target: &Path) -> String {
    let from_parts: Vec<_> = from_dir.components().collect();
    let target_parts: Vec<_> = target.components().collect();

    let mut common = 0;
    while common < from_parts.len()
        && common < target_parts.len()
        && from_parts[common] == target_parts[common]
    {
        common += 1;
    }

    let mut import_path = String::new();
    let ups = from_parts.len().saturating_sub(common);
    if ups == 0 {
        import_path.push_str("./");
    } else {
        for _ in 0..ups {
            import_path.push_str("../");
        }
    }

    for (index, part) in target_parts[common..].iter().enumerate() {
        if index > 0 {
            import_path.push('/');
        }
        import_path.push_str(&part.as_os_str().to_string_lossy());
    }

    import_path
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn empty_registry() {
        let result = generate_registry(&HashMap::new(), &[], &[], &[]);
        assert!(result.contains("registerComponent"));
        assert!(result.contains("registerPage"));
        assert!(result.contains("markMounted"));
        assert!(result.contains("import type { TinyFxContext, RouteDef }"));
        assert!(!result.contains("import * as"));
        assert!(result.contains("init({ routes, setupDirectives })"));
        assert!(result.contains("const routes: Record<string, RouteDef>"));
        assert!(!result.contains("effect,"));
    }

    #[test]
    fn effect_imported_when_signal_each_sites_exist() {
        let directives = vec![PageDirectives {
            page_name: "index".to_string(),
            each_sites: vec![super::super::each::EachSite {
                id: "index_each_0".to_string(),
                source: super::super::codegen::LoopSource::Signal("items".to_string()),
                item_var: "item".to_string(),
                key_strategy: super::super::each::KeyStrategy::Index,
                template_html: "<div></div>".to_string(),
                bindings: Vec::new(),
                has_dynamic_components: false,
                dynamic_component_names: Vec::new(),
            }],
            if_sites: Vec::new(),
        }];

        let result = generate_registry(&HashMap::new(), &[], &directives, &[]);
        assert!(result.contains("effect,"));
        assert!(result.contains("effect(() => __reconcile_index_each_0"));
        assert!(result.contains("init({ routes, setupDirectives })"));
    }

    #[test]
    fn effect_imported_when_signal_if_sites_exist() {
        use super::super::conditional::{IfBranch, IfSite};

        let directives = vec![PageDirectives {
            page_name: "index".to_string(),
            each_sites: Vec::new(),
            if_sites: vec![IfSite {
                id: "index_if_0".to_string(),
                branches: vec![IfBranch {
                    condition: Some("isLoggedIn()".to_string()),
                    is_signal: true,
                    html: "<div></div>".to_string(),
                    dynamic_component_names: Vec::new(),
                }],
            }],
        }];

        let result = generate_registry(&HashMap::new(), &[], &directives, &[]);
        assert!(result.contains("effect,"));
        assert!(result.contains("effect(() => __toggle_index_if_0"));
    }

    #[test]
    fn effect_not_imported_for_plain_each_sites() {
        let directives = vec![PageDirectives {
            page_name: "index".to_string(),
            each_sites: vec![super::super::each::EachSite {
                id: "index_each_0".to_string(),
                source: super::super::codegen::LoopSource::Plain("items".to_string()),
                item_var: "item".to_string(),
                key_strategy: super::super::each::KeyStrategy::Index,
                template_html: "<div></div>".to_string(),
                bindings: Vec::new(),
                has_dynamic_components: false,
                dynamic_component_names: Vec::new(),
            }],
            if_sites: Vec::new(),
        }];

        let result = generate_registry(&HashMap::new(), &[], &directives, &[]);
        assert!(!result.contains("effect,"));
        assert!(result.contains("__reconcile_index_each_0"));
        assert!(!result.contains("effect(() => __reconcile_index_each_0"));
        assert!(result.contains("init({ routes, setupDirectives })"));
        assert!(!result.contains("init({ routes, setupDirectives, effect })"));
    }

    #[test]
    fn effect_not_imported_for_plain_if_sites() {
        use super::super::conditional::{IfBranch, IfSite};

        let directives = vec![PageDirectives {
            page_name: "index".to_string(),
            each_sites: Vec::new(),
            if_sites: vec![IfSite {
                id: "index_if_0".to_string(),
                branches: vec![IfBranch {
                    condition: Some("true".to_string()),
                    is_signal: false,
                    html: "<div></div>".to_string(),
                    dynamic_component_names: Vec::new(),
                }],
            }],
        }];

        let result = generate_registry(&HashMap::new(), &[], &directives, &[]);
        assert!(!result.contains("effect,"));
        assert!(result.contains("__toggle_index_if_0"));
        assert!(!result.contains("effect(() => __toggle_index_if_0"));
    }

    #[test]
    fn each_helpers_are_emitted_without_runtime_imports() {
        let directives = vec![PageDirectives {
            page_name: "index".to_string(),
            each_sites: vec![super::super::each::EachSite {
                id: "index_each_0".to_string(),
                source: super::super::codegen::LoopSource::Range(0, 1),
                item_var: "i".to_string(),
                key_strategy: super::super::each::KeyStrategy::Index,
                template_html: "<div></div>".to_string(),
                bindings: Vec::new(),
                has_dynamic_components: false,
                dynamic_component_names: Vec::new(),
            }],
            if_sites: Vec::new(),
        }];

        let result = generate_registry(&HashMap::new(), &[], &directives, &[]);
        assert!(result.contains("function __destroyNode"));
        assert!(result.contains("function __registerInstance"));
        assert!(!result.contains("destroyNode as __destroyNode"));
        assert!(!result.contains("registerInstance as __registerInstance"));
    }

    #[test]
    fn mount_component_uses_mark_mounted() {
        let result = generate_registry(&HashMap::new(), &[], &[], &[]);
        assert!(result.contains("if (!markMounted(el)) return undefined;"));
        assert!(!result.contains("dataset.tinyfxMounted"));
    }

    #[test]
    fn routes_emit_pre_split_segments() {
        let pages = vec![PageDef {
            name: "blog".to_string(),
            route: "/blog/:slug".to_string(),
            html: String::new(),
            source_path: std::path::PathBuf::from("src/pages/blog.html"),
            out_path: std::path::PathBuf::from("dist/blog.html"),
        }];

        let result = generate_registry(&HashMap::new(), &pages, &[], &[]);
        assert!(result.contains("staticSegments: [\"blog\", null]"));
        assert!(result.contains("paramNames: [\"slug\"]"));
    }

    #[test]
    fn relative_import_same_parent() {
        let result = relative_import(Path::new("src"), Path::new("src/components/Button/Button"));
        assert_eq!(result, "./components/Button/Button");
    }

    #[test]
    fn relative_import_sibling() {
        let result = relative_import(
            Path::new("src/lib"),
            Path::new("src/components/Button/Button"),
        );
        assert_eq!(result, "../components/Button/Button");
    }
}
