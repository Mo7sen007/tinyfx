use std::collections::HashSet;
use std::path::Path;

/// Generate `tinyfx.gen.ts` — the component mount registry.
///
/// For each used component that has a `.ts` file exporting a `mount()` factory,
/// emit an import and wire it into `setupComponents(container)`.
/// Returns class instances for optional teardown (e.g. calling `destroy()`).
///
/// `src_dir` is the directory where `tinyfx.gen.ts` will live (e.g. `src/`).
/// Import paths are computed relative to that location.
pub fn generate_registry(used: &HashSet<String>, components_dir: &Path, src_dir: &Path) -> String {
    let mut imports = Vec::new();
    let mut entries = Vec::new();

    let mut names: Vec<&String> = used.iter().collect();
    names.sort(); // deterministic output

    for name in &names {
        let ts_path = components_dir
            .join(name.as_str())
            .join(format!("{}.ts", name));
        if ts_path.exists() {
            // Compute relative path from src_dir (where gen file lives) to the .ts file
            let import_path = relative_import(
                src_dir,
                &components_dir.join(name.as_str()).join(name.as_str()),
            );
            let alias = format!("{}mount", name);
            imports.push(format!(
                "import {{ mount as {} }} from \"{}\";",
                alias, import_path
            ));
            entries.push(format!("  \"{}\": {},", name, alias));
        }
    }

    let mut out = String::new();

    out.push_str("// Auto-generated by tinyfx build — do not edit.\n");
    out.push_str("// This file wires component mount() factories to data-component attributes.\n");
    out.push('\n');
    out.push_str("import { Container } from \"@tinyfx/runtime/di\";\n");
    out.push_str("import type { TinyFxContext } from \"@tinyfx/runtime/di\";\n");
    out.push('\n');

    if imports.is_empty() {
        // No components have behavior — emit a no-op registry
        out.push_str(
            "const registry: Record<string, (el: HTMLElement, ctx: TinyFxContext) => any> = {};\n",
        );
    } else {
        for imp in &imports {
            out.push_str(imp);
            out.push('\n');
        }
        out.push('\n');
        out.push_str(
            "const registry: Record<string, (el: HTMLElement, ctx: TinyFxContext) => any> = {\n",
        );
        for entry in &entries {
            out.push_str(entry);
            out.push('\n');
        }
        out.push_str("};\n");
    }

    out.push('\n');
    out.push_str("/**\n");
    out.push_str(" * Initialize all components with a DI container.\n");
    out.push_str(" * Call this from main.ts after registering services.\n");
    out.push_str(" */\n");
    out.push_str("export function setupComponents(\n");
    out.push_str("  container: Container,\n");
    out.push_str("  root: Document | HTMLElement = document,\n");
    out.push_str(") {\n");
    out.push_str("  const ctx: TinyFxContext = { container };\n");
    out.push_str("  const instances: any[] = [];\n");
    out.push_str("  root.querySelectorAll(\"[data-component]\").forEach((el) => {\n");
    out.push_str("    const name = el.getAttribute(\"data-component\");\n");
    out.push_str("    if (name && registry[name]) {\n");
    out.push_str("      const inst = registry[name](el as HTMLElement, ctx);\n");
    out.push_str("      if (inst) instances.push(inst);\n");
    out.push_str("    }\n");
    out.push_str("  });\n");
    out.push_str("  return instances;\n");
    out.push_str("}\n");

    out
}

/// Compute a relative import path from `from_dir` to `target` (without extension).
/// Both should be relative to the project root.
fn relative_import(from_dir: &Path, target: &Path) -> String {
    let from_parts: Vec<_> = from_dir.components().collect();
    let to_parts: Vec<_> = target.components().collect();

    // Find common prefix length
    let mut common = 0;
    while common < from_parts.len()
        && common < to_parts.len()
        && from_parts[common] == to_parts[common]
    {
        common += 1;
    }

    let mut result = String::new();
    let ups = from_parts.len() - common;
    if ups == 0 {
        result.push_str("./");
    } else {
        for _ in 0..ups {
            result.push_str("../");
        }
    }

    for (i, part) in to_parts[common..].iter().enumerate() {
        if i > 0 {
            result.push('/');
        }
        result.push_str(&part.as_os_str().to_string_lossy());
    }

    result
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;
    use std::path::Path;

    #[test]
    fn empty_registry() {
        let used = HashSet::new();
        let result = generate_registry(&used, Path::new("src/components"), Path::new("src"));
        assert!(result.contains("const registry"));
        assert!(result.contains("setupComponents"));
        assert!(result.contains("import { Container }"));
        assert!(!result.contains("import { mount"));
        // Legacy initComponents was removed — should NOT be present
        assert!(!result.contains("initComponents"));
    }

    #[test]
    fn relative_import_same_parent() {
        let result = relative_import(Path::new("src"), Path::new("src/components/Button/Button"));
        assert_eq!(result, "./components/Button/Button");
    }

    #[test]
    fn relative_import_sibling() {
        let result = relative_import(
            Path::new("src/lib"),
            Path::new("src/components/Button/Button"),
        );
        assert_eq!(result, "../components/Button/Button");
    }
}
