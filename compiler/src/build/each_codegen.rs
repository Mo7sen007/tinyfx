//! # each_codegen
//!
//! TypeScript generation for TinyFX `<each>` directive sites.
//!
//! This module emits per-site node record types, create/update/reconcile
//! helpers, and directive wiring statements.

use std::sync::OnceLock;

use regex::Regex;

use super::codegen::{DirectiveContext, LoopSource, TsBuffer, qualify_expr};
use super::each::{BindingKind, EachSite, KeyStrategy};

/// Generate all TypeScript code for one `<each>` site.
#[allow(dead_code)]
pub fn generate_each_code(site: &EachSite, context: &DirectiveContext, buf: &mut TsBuffer) {
    generate_each_helpers(site, context, buf);
    generate_each_wiring(site, context, buf);
}

/// Generate the site-specific node record interface.
///
/// The emitted interface contains `el`, `key`, and one `__b_*` field per
/// extracted template binding. Binding fields are stable DOM references used
/// by `__update_*` without additional selector lookups.
pub fn generate_each_node_record(site: &EachSite, _context: &DirectiveContext, buf: &mut TsBuffer) {
    buf.line(&format!(
        "// <each> site {} source=\"{}\"",
        site.id,
        source_expression(site)
    ));
    buf.line(&format!("interface NodeRecord_{} {{", site.id));
    buf.indent();
    buf.line("el: HTMLElement;");
    buf.line("key: string;");
    for binding in &site.bindings {
        buf.line(&format!(
            "{}: HTMLElement;",
            binding_field_name(&binding.field)
        ));
    }
    buf.dedent();
    buf.line("}");
    buf.blank();
}

/// Generate helper functions for one `<each>` site.
///
/// Emits declaration order required by generated code:
/// 1. closure-level node map
/// 2. create function
/// 3. update function
/// 4. reconcile function
pub fn generate_each_helpers(site: &EachSite, _context: &DirectiveContext, buf: &mut TsBuffer) {
    generate_each_node_record(site, _context, buf);
    generate_node_map_declaration(site, buf);
    generate_create_fn(site, buf);
    generate_update_fn(site, buf);
    generate_reconcile_fn(site, buf);
}

/// Generate runtime wiring calls for one `<each>` site.
///
/// Page-level sites are wired in `setupDirectives(ctx)` and pass `ctx` to the
/// reconciler. Component-level wiring is generated by `wrapper.rs` so no code
/// is emitted here for component context.
pub fn generate_each_wiring(site: &EachSite, context: &DirectiveContext, buf: &mut TsBuffer) {
    let DirectiveContext::Page { module_alias } = context else {
        return;
    };

    buf.line(&format!(
        "const __container_{} = document.querySelector(\"[data-each='{}']\") as HTMLElement | null;",
        site.id, site.id
    ));
    buf.line(&format!("if (__container_{}) {{", site.id));
    buf.indent();

    match &site.source {
        LoopSource::Signal(name) => {
            let qualified = qualify_expr(&format!("{}()", name), module_alias);
            buf.line(&format!(
                "effect(() => __reconcile_{}(__container_{}, {} as any[], ctx));",
                site.id, site.id, qualified
            ));
        }
        LoopSource::Plain(expr) => {
            let qualified = qualify_expr(expr, module_alias);
            buf.line(&format!(
                "__reconcile_{}(__container_{}, {} as any[], ctx);",
                site.id, site.id, qualified
            ));
        }
        LoopSource::Range(start, end) => {
            let len = end.saturating_sub(*start);
            buf.line(&format!(
                "const __items_{} = Array.from({{ length: {} }}, (_, __idx) => __idx + {});",
                site.id, len, start
            ));
            buf.line(&format!(
                "__reconcile_{}(__container_{}, __items_{} as any[], ctx);",
                site.id, site.id, site.id
            ));
        }
    }

    buf.dedent();
    buf.line("}");
    buf.blank();
}

fn generate_node_map_declaration(site: &EachSite, buf: &mut TsBuffer) {
    buf.line(&format!(
        "// Closure-level node map for this site; persists across reconcile calls."
    ));
    buf.line(&format!(
        "const __nodes_{} = new Map<string, NodeRecord_{}>();",
        site.id, site.id
    ));
    buf.blank();
}

fn generate_create_fn(site: &EachSite, buf: &mut TsBuffer) {
    let signature = match site.key_strategy {
        KeyStrategy::Keyed { .. } => format!(
            "function __create_{}({}: any): NodeRecord_{} {{",
            site.id, site.item_var, site.id
        ),
        KeyStrategy::Index => format!(
            "function __create_{}({}: any, __idx: number): NodeRecord_{} {{",
            site.id, site.item_var, site.id
        ),
    };

    buf.line(&signature);
    buf.indent();
    buf.line("const __wrapper = document.createElement(\"div\");");
    buf.line(&format!(
        "__wrapper.innerHTML = {};",
        html_template_literal(&site.template_html)
    ));
    buf.line("const el = __wrapper.firstElementChild as HTMLElement;");
    buf.line(&format!(
        "if (!el) throw new Error(\"tinyfx <each> create failed for site {}\");",
        site.id
    ));

    match &site.key_strategy {
        KeyStrategy::Keyed { field_name } => {
            buf.line(&format!(
                "el.dataset.key = String({}.{});",
                site.item_var,
                field_name.trim()
            ));
        }
        KeyStrategy::Index => {
            buf.line("el.dataset.key = String(__idx);");
        }
    }

    for binding in &site.bindings {
        let field_ref = binding_field_name(&binding.field);
        let selector_var = format!("__sel_{}", binding.field);
        buf.line(&format!(
            "const {} = \"{}\";",
            selector_var,
            escape_ts_string(&binding.selector)
        ));
        buf.line(&format!(
            "const {} = (el.matches({}) ? el : el.querySelector<HTMLElement>({}));",
            field_ref, selector_var, selector_var
        ));
        buf.line(&format!(
            "if (!{}) throw new Error(\"tinyfx <each> binding selector not found for site {} field {}\");",
            field_ref, site.id, binding.field
        ));
    }

    if !site.bindings.is_empty() {
        buf.blank();
    }

    for binding in &site.bindings {
        let field_ref = binding_field_name(&binding.field);
        match &binding.kind {
            BindingKind::TextContent => {
                buf.line(&format!(
                    "{}.textContent = String({}.{});",
                    field_ref, site.item_var, binding.field
                ));
            }
            BindingKind::Attribute(attr_name) => {
                buf.line(&format!(
                    "{}.setAttribute(\"{}\", {});",
                    field_ref,
                    escape_ts_string(attr_name),
                    attribute_value_expression(binding, &site.item_var)
                ));
            }
        }
    }

    if !site.bindings.is_empty() {
        buf.blank();
    }

    buf.line("const key = el.dataset.key ?? \"\";");
    buf.line("return {");
    buf.indent();
    buf.line("el,");
    buf.line("key,");
    for binding in &site.bindings {
        let field_ref = binding_field_name(&binding.field);
        buf.line(&format!("{},", field_ref));
    }
    buf.dedent();
    buf.line("};");
    buf.dedent();
    buf.line("}");
    buf.blank();
}

fn generate_update_fn(site: &EachSite, buf: &mut TsBuffer) {
    buf.line(&format!(
        "function __update_{}({}: any, node: NodeRecord_{}): void {{",
        site.id, site.item_var, site.id
    ));
    buf.indent();
    for binding in &site.bindings {
        let field_ref = format!("node.{}", binding_field_name(&binding.field));
        match &binding.kind {
            BindingKind::TextContent => {
                buf.line(&format!(
                    "{}.textContent = String({}.{});",
                    field_ref, site.item_var, binding.field
                ));
            }
            BindingKind::Attribute(attr_name) => {
                buf.line(&format!(
                    "{}.setAttribute(\"{}\", {});",
                    field_ref,
                    escape_ts_string(attr_name),
                    attribute_value_expression(binding, &site.item_var)
                ));
            }
        }
    }
    buf.dedent();
    buf.line("}");
    buf.blank();
}

// FUTURE: Support hydration by allowing __create_* to adopt an existing element instead of always creating new DOM.
// FUTURE: Support per-binding fine-grained effects where each TemplateBinding updates independently.
fn generate_reconcile_fn(site: &EachSite, buf: &mut TsBuffer) {
    buf.line(&format!(
        "function __reconcile_{}(container: HTMLElement, items: any[], ctx: TinyFxContext): void {{",
        site.id
    ));
    buf.indent();
    buf.line("// Phase 1: resolve next state");
    buf.line(&format!("const next: NodeRecord_{}[] = [];", site.id));
    buf.line("for (let __idx = 0; __idx < items.length; __idx++) {");
    buf.indent();
    buf.line(&format!("const {} = items[__idx];", site.item_var));
    match &site.key_strategy {
        KeyStrategy::Keyed { field_name } => {
            buf.line(&format!(
                "const key = String({}.{});",
                site.item_var,
                field_name.trim()
            ));
        }
        KeyStrategy::Index => {
            buf.line("const key = String(__idx);");
        }
    }
    buf.line(&format!("const existing = __nodes_{}.get(key);", site.id));
    buf.line("if (existing) {");
    buf.indent();
    buf.line(&format!(
        "__update_{}({}, existing);",
        site.id, site.item_var
    ));
    buf.line("next.push(existing);");
    buf.dedent();
    buf.line("} else {");
    buf.indent();
    match site.key_strategy {
        KeyStrategy::Keyed { .. } => {
            buf.line(&format!(
                "const record = __create_{}({});",
                site.id, site.item_var
            ));
        }
        KeyStrategy::Index => {
            buf.line(&format!(
                "const record = __create_{}({}, __idx);",
                site.id, site.item_var
            ));
        }
    }
    buf.line(&format!("__nodes_{}.set(record.key, record);", site.id));
    buf.line("next.push(record);");
    buf.dedent();
    buf.line("}");
    buf.dedent();
    buf.line("}");
    buf.blank();

    buf.line("// Phase 2: remove stale nodes");
    buf.line("const nextKeys = new Set(next.map((record) => record.key));");
    buf.line(&format!(
        "for (const [key, record] of __nodes_{}) {{",
        site.id
    ));
    buf.indent();
    buf.line("if (!nextKeys.has(key)) {");
    buf.indent();
    buf.line("__destroyNode(record.el);");
    buf.line("if (container.contains(record.el)) container.removeChild(record.el);");
    buf.line(&format!("__nodes_{}.delete(key);", site.id));
    buf.dedent();
    buf.line("}");
    buf.dedent();
    buf.line("}");
    buf.blank();

    buf.line("// Phase 3: sync DOM order");
    buf.line("for (let i = 0; i < next.length; i++) {");
    buf.indent();
    buf.line("const record = next[i];");
    buf.line("const currentAtIndex = container.children[i];");
    buf.line("if (!container.contains(record.el)) {");
    buf.indent();
    buf.line("container.insertBefore(record.el, currentAtIndex ?? null);");
    buf.line(
        "record.el.querySelectorAll<HTMLElement>(\"[data-component]:not([data-tinyfx-mounted])\").forEach((node) => {",
    );
    buf.indent();
    buf.line("const name = node.getAttribute(\"data-component\");");
    buf.line("if (name && registry[name]) registry[name](node, ctx);");
    buf.dedent();
    buf.line("});");
    buf.dedent();
    buf.line("} else if (currentAtIndex !== record.el) {");
    buf.indent();
    buf.line("container.insertBefore(record.el, currentAtIndex ?? null);");
    buf.dedent();
    buf.line("}");
    buf.dedent();
    buf.line("}");
    buf.dedent();
    buf.line("}");
    buf.blank();
}

fn source_expression(site: &EachSite) -> String {
    match &site.source {
        LoopSource::Signal(name) => format!("{}()", name),
        LoopSource::Plain(expr) => expr.trim().to_string(),
        LoopSource::Range(start, end) => format!("{}..{}", start, end),
    }
}

fn binding_field_name(field: &str) -> String {
    let mut normalized = String::new();
    for ch in field.chars() {
        if ch.is_ascii_alphanumeric() || ch == '_' {
            normalized.push(ch);
        } else {
            normalized.push('_');
        }
    }
    format!("__b_{}", normalized)
}

fn html_template_literal(template_html: &str) -> String {
    let escaped = template_html
        .replace('\\', "\\\\")
        .replace('`', "\\`")
        .replace("${", "\\${");
    format!("`{}`", escaped)
}

fn escape_ts_string(input: &str) -> String {
    input.replace('\\', "\\\\").replace('"', "\\\"")
}

fn attribute_value_expression(binding: &super::each::TemplateBinding, item_var: &str) -> String {
    let default_expr = format!("String({}.{})", item_var, binding.field);
    let Some(template) = &binding.attr_template else {
        return default_expr;
    };

    if !template.contains("{{") {
        return default_expr;
    }

    let token_a = format!("{}.{}", item_var, binding.field);
    let token_b = binding.field.clone();
    let mut rendered = template.clone();
    rendered = moustache_re()
        .replace_all(&rendered, |caps: &regex::Captures| {
            let raw = caps.get(1).map(|m| m.as_str()).unwrap_or_default().trim();
            if raw == token_a || raw == token_b {
                format!("${{{}}}", default_expr)
            } else {
                "".to_string()
            }
        })
        .to_string();

    format!("`{}`", escape_ts_template_literal(&rendered))
}

fn escape_ts_template_literal(input: &str) -> String {
    input
        .replace('\\', "\\\\")
        .replace('`', "\\`")
        .replace("${", "\\${")
        .replace("\\${String", "${String")
}

fn moustache_re() -> &'static Regex {
    static REGEX: OnceLock<Regex> = OnceLock::new();
    REGEX.get_or_init(|| Regex::new(r#"\{\{\s*([^}]+)\s*\}\}"#).expect("valid moustache regex"))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::build::codegen::LoopSource;
    use crate::build::each::{BindingKind, TemplateBinding};

    fn mk_site(key_strategy: KeyStrategy) -> EachSite {
        EachSite {
            id: "index_each_0".to_string(),
            source: LoopSource::Signal("items".to_string()),
            item_var: "item".to_string(),
            key_strategy,
            template_html: "<div class=\"row\"><span class=\"title\"></span></div>".to_string(),
            bindings: vec![TemplateBinding {
                field: "title".to_string(),
                selector: "span.title".to_string(),
                kind: BindingKind::TextContent,
                attr_template: None,
            }],
            has_dynamic_components: false,
            dynamic_component_names: Vec::new(),
        }
    }

    #[test]
    fn codegen_create_fn_index_keyed_uses_idx_param() {
        let site = mk_site(KeyStrategy::Index);
        let mut buf = TsBuffer::new();
        generate_each_helpers(&site, &DirectiveContext::Component, &mut buf);
        let code = buf.build();
        assert!(code.contains(
            "function __create_index_each_0(item: any, __idx: number): NodeRecord_index_each_0"
        ));
        assert!(code.contains("el.dataset.key = String(__idx);"));
    }

    #[test]
    fn codegen_reconcile_fn_has_ctx_param() {
        let site = mk_site(KeyStrategy::Keyed {
            field_name: "id".to_string(),
        });
        let mut buf = TsBuffer::new();
        generate_each_helpers(
            &site,
            &DirectiveContext::Page {
                module_alias: "PageModule0".to_string(),
            },
            &mut buf,
        );
        let code = buf.build();
        assert!(code.contains("function __reconcile_index_each_0(container: HTMLElement, items: any[], ctx: TinyFxContext): void"));
    }

    #[test]
    fn codegen_reconcile_fn_three_phase_comments() {
        let site = mk_site(KeyStrategy::Index);
        let mut buf = TsBuffer::new();
        generate_each_helpers(&site, &DirectiveContext::Component, &mut buf);
        let code = buf.build();
        assert!(code.contains("// Phase 1: resolve next state"));
        assert!(code.contains("// Phase 2: remove stale nodes"));
        assert!(code.contains("// Phase 3: sync DOM order"));
    }

    #[test]
    fn codegen_node_map_declaration_emitted() {
        let site = mk_site(KeyStrategy::Index);
        let mut buf = TsBuffer::new();
        generate_each_helpers(&site, &DirectiveContext::Component, &mut buf);
        let code = buf.build();
        let map_pos = code
            .find("const __nodes_index_each_0 = new Map<string, NodeRecord_index_each_0>();")
            .expect("map declaration should exist");
        let create_pos = code
            .find("function __create_index_each_0")
            .expect("create function should exist");
        assert!(map_pos < create_pos);
    }

    #[test]
    fn codegen_update_fn_no_queryselector() {
        let site = mk_site(KeyStrategy::Keyed {
            field_name: "id".to_string(),
        });
        let mut buf = TsBuffer::new();
        generate_each_helpers(&site, &DirectiveContext::Component, &mut buf);
        let code = buf.build();
        let update_start = code
            .find("function __update_index_each_0")
            .expect("update function should exist");
        let reconcile_start = code
            .find("function __reconcile_index_each_0")
            .expect("reconcile function should exist");
        assert!(!code[update_start..reconcile_start].contains("querySelector"));
    }

    #[test]
    fn codegen_create_fn_handles_root_selector_with_matches() {
        let mut site = mk_site(KeyStrategy::Keyed {
            field_name: "id".to_string(),
        });
        site.bindings = vec![TemplateBinding {
            field: "own".to_string(),
            selector: "div.message".to_string(),
            kind: BindingKind::Attribute("class".to_string()),
            attr_template: Some("message {{own}}".to_string()),
        }];

        let mut buf = TsBuffer::new();
        generate_each_helpers(&site, &DirectiveContext::Component, &mut buf);
        let code = buf.build();

        assert!(
            code.contains("el.matches(__sel_own) ? el : el.querySelector<HTMLElement>(__sel_own)")
        );
    }

    #[test]
    fn codegen_create_fn_no_partial_node_record_fallback() {
        let site = mk_site(KeyStrategy::Index);
        let mut buf = TsBuffer::new();
        generate_each_helpers(&site, &DirectiveContext::Component, &mut buf);
        let code = buf.build();

        assert!(!code.contains("as NodeRecord_index_each_0"));
        assert!(code.contains(
            "if (!el) throw new Error(\"tinyfx <each> create failed for site index_each_0\")"
        ));
    }

    #[test]
    fn codegen_attribute_template_preserves_static_class_segment() {
        let mut site = mk_site(KeyStrategy::Keyed {
            field_name: "id".to_string(),
        });
        site.bindings = vec![TemplateBinding {
            field: "own".to_string(),
            selector: "div.message".to_string(),
            kind: BindingKind::Attribute("class".to_string()),
            attr_template: Some("message {{own}}".to_string()),
        }];

        let mut buf = TsBuffer::new();
        generate_each_helpers(&site, &DirectiveContext::Component, &mut buf);
        let code = buf.build();

        assert!(code.contains("setAttribute(\"class\", `message ${String(item.own)}`);"));
    }
}
