use std::collections::HashMap;

use crate::build::pages::PageDef;
use super::CompiledComponent;

/// Generate tinyfx.gen.ts — the component init registry.
///
/// For each used component that has a .ts file with an init() export,
/// emit an import and wire it into initComponents().
pub fn generate_registry(
    registry: &HashMap<String, CompiledComponent>,
    pages: &[PageDef],
) -> String {
    let mut imports = Vec::new();
    let mut entries = Vec::new();
    let mut page_imports = Vec::new();
    let mut page_entries = Vec::new();

    let src_dir = super::infer_src_dir(registry, pages);

    let mut components: Vec<&CompiledComponent> = registry.values().collect();
    components.sort_by(|a, b| a.name.cmp(&b.name)); // deterministic output

    for component in components {
        if !component.is_dynamic {
            continue;
        }

        let ts_path = component.path.with_extension("ts");
        if ts_path.exists() {
            // Compute relative path from src_dir (where gen file lives) to component module.
            let import_path = super::relative_import(&src_dir, &ts_path.with_extension(""));
            let alias = format!("{}Module", component.name);
            imports.push(format!(
                "import * as {} from \"{}\";",
                alias, import_path
            ));
            entries.push(format!(
                "  \"{}\": (el, ctx) => mountComponent({}, el, ctx),",
                component.name, alias
            ));
        }
    }

    let mut page_defs = pages.to_vec();
    page_defs.sort_by(|a, b| a.route.cmp(&b.route));

    for (idx, page) in page_defs.iter().enumerate() {
        let ts_path = page.source_path.with_extension("ts");
        if ts_path.exists() {
            let import_path = super::relative_import(&src_dir, &ts_path.with_extension(""));
            let alias = format!("PageModule{}", idx);
            page_imports.push(format!("import * as {} from \"{}\";", alias, import_path));
            page_entries.push(format!("  \"{}\": {},", page.route, alias));
        }
    }

    let mut out = String::new();

    out.push_str("// Auto-generated by tinyfx build — do not edit.\n");
    out.push_str("// This file wires component mount() factories to data-component attributes.\n");
    out.push('\n');
    out.push_str("import { initRouter, navigate } from \"@tinyfx/runtime\";\n");
    out.push_str("import type { TinyFxContext } from \"@tinyfx/runtime\";\n");
    out.push('\n');

    out.push_str("type ComponentModule = {\n");
    out.push_str("  mount?: (el: HTMLElement, ctx: TinyFxContext) => any;\n");
    out.push_str("  init?: (el: HTMLElement, ctx: TinyFxContext) => void;\n");
    out.push_str("};\n\n");

    out.push_str("type PageModule = {\n");
    out.push_str("  init?: (el: HTMLElement, ctx: TinyFxContext) => void;\n");
    out.push_str("};\n\n");

    out.push_str("function mountComponent(module: ComponentModule, el: HTMLElement, ctx: TinyFxContext) {\n");
    out.push_str("  if (el.dataset.tinyfxMounted === \"true\") return undefined;\n");
    out.push_str("  el.dataset.tinyfxMounted = \"true\";\n");
    out.push_str("  if (typeof module.mount === \"function\") {\n");
    out.push_str("    return module.mount(el, ctx);\n");
    out.push_str("  }\n");
    out.push_str("  if (typeof module.init === \"function\") {\n");
    out.push_str("    module.init(el, ctx);\n");
    out.push_str("  }\n");
    out.push_str("  return undefined;\n");
    out.push_str("}\n\n");

    if imports.is_empty() {
        // No components have behavior — emit a no-op registry
        out.push_str(
            "const registry: Record<string, (el: HTMLElement, ctx: TinyFxContext) => any> = {};\n",
        );
    } else {
        for imp in &imports {
            out.push_str(imp);
            out.push('\n');
        }
        out.push('\n');
        out.push_str(
            "const registry: Record<string, (el: HTMLElement, ctx: TinyFxContext) => any> = {\n",
        );
        for entry in &entries {
            out.push_str(entry);
            out.push('\n');
        }
        out.push_str("};\n");
    }

    out.push('\n');
    for imp in &page_imports {
        out.push_str(imp);
        out.push('\n');
    }
    if !page_imports.is_empty() {
        out.push('\n');
    }

    out.push_str("const routes = {\n");
    for page in &page_defs {
        out.push_str(&format!(
            "  \"{}\": {{ page: \"{}\", path: \"{}\" }},\n",
            page.route, page.name, page.route
        ));
    }
    out.push_str("} as const;\n\n");

    if page_entries.is_empty() {
        out.push_str("const pageModules: Record<string, PageModule> = {};\n\n");
    } else {
        out.push_str("const pageModules: Record<string, PageModule> = {\n");
        for entry in &page_entries {
            out.push_str(entry);
            out.push('\n');
        }
        out.push_str("};\n\n");
    }

    out.push_str("function matchesRoute(pattern: string, pathname: string): boolean {\n");
    out.push_str("  const patternParts = pattern.split(\"/\").filter(Boolean);\n");
    out.push_str("  const pathParts = pathname.split(\"/\").filter(Boolean);\n");
    out.push_str("  if (patternParts.length !== pathParts.length) return false;\n");
    out.push_str("  for (let i = 0; i < patternParts.length; i++) {\n");
    out.push_str("    const segment = patternParts[i];\n");
    out.push_str("    if (segment.startsWith(\":\")) continue;\n");
    out.push_str("    if (segment !== pathParts[i]) return false;\n");
    out.push_str("  }\n");
    out.push_str("  return true;\n");
    out.push_str("}\n\n");

    out.push_str("function extractParams(pattern: string, pathname: string): Record<string, string> {\n");
    out.push_str("  const patternParts = pattern.split(\"/\").filter(Boolean);\n");
    out.push_str("  const pathParts = pathname.split(\"/\").filter(Boolean);\n");
    out.push_str("  const params: Record<string, string> = {};\n");
    out.push_str("  for (let i = 0; i < patternParts.length; i++) {\n");
    out.push_str("    const segment = patternParts[i];\n");
    out.push_str("    if (!segment.startsWith(\":\")) continue;\n");
    out.push_str("    const key = segment.slice(1);\n");
    out.push_str("    params[key] = decodeURIComponent(pathParts[i] ?? \"\");\n");
    out.push_str("  }\n");
    out.push_str("  return params;\n");
    out.push_str("}\n\n");

    out.push_str("function createContext(pattern: string): TinyFxContext {\n");
    out.push_str("  return { params: extractParams(pattern, window.location.pathname), navigate };\n");
    out.push_str("}\n\n");

    out.push_str("function resolveCurrentPattern(pathname: string): string | null {\n");
    out.push_str("  for (const pattern of Object.keys(routes)) {\n");
    out.push_str("    if (matchesRoute(pattern, pathname)) return pattern;\n");
    out.push_str("  }\n");
    out.push_str("  return null;\n");
    out.push_str("}\n\n");

    out.push_str("function runPageInit(pattern: string, ctx: TinyFxContext): void {\n");
    out.push_str("  const pathname = window.location.pathname;\n");
    out.push_str("  if (!matchesRoute(pattern, pathname)) return;\n");
    out.push_str("  const mod = pageModules[pattern];\n");
    out.push_str("  if (typeof mod?.init === \"function\") {\n");
    out.push_str("    mod.init(document.body, ctx);\n");
    out.push_str("  }\n");
    out.push_str("}\n\n");

    out.push_str("initRouter(routes);\n\n");

    out.push_str("let bootstrapped = false;\n\n");

    out.push_str("export function bootstrapTinyFx(root: Document | HTMLElement = document) {\n");
    out.push_str("  if (bootstrapped) return [];\n");
    out.push_str("  bootstrapped = true;\n");
    out.push_str("  const pattern = resolveCurrentPattern(window.location.pathname) ?? \"/\";\n");
    out.push_str("  const ctx = createContext(pattern);\n");
    out.push_str("  const instances = setupComponents(ctx, root);\n");
    out.push_str("  runPageInit(pattern, ctx);\n");
    out.push_str("  return instances;\n");
    out.push_str("}\n\n");

    out.push_str("if (typeof document !== \"undefined\") {\n");
    out.push_str("  if (document.readyState === \"loading\") {\n");
    out.push_str("    document.addEventListener(\"DOMContentLoaded\", () => {\n");
    out.push_str("      bootstrapTinyFx();\n");
    out.push_str("    }, { once: true });\n");
    out.push_str("  } else {\n");
    out.push_str("    bootstrapTinyFx();\n");
    out.push_str("  }\n");
    out.push_str("}\n\n");

    out.push_str("/**\n");
    out.push_str(" * Initialize all components with a TinyFxContext.\n");
    out.push_str(" * This is exported for remounting dynamic DOM after the initial bootstrap.\n");
    out.push_str(" */\n");
    out.push_str("export function setupComponents(\n");
    out.push_str("  ctx: TinyFxContext,\n");
    out.push_str("  root: Document | HTMLElement = document,\n");
    out.push_str(") {\n");
    out.push_str("  const instances: any[] = [];\n");
    out.push_str("  root.querySelectorAll(\"[data-component]\").forEach((el) => {\n");
    out.push_str("    const name = el.getAttribute(\"data-component\");\n");
    out.push_str("    if (name && registry[name]) {\n");
    out.push_str("      const inst = registry[name](el as HTMLElement, ctx);\n");
    out.push_str("      if (inst) instances.push(inst);\n");
    out.push_str("    }\n");
    out.push_str("  });\n");
    out.push_str("  return instances;\n");
    out.push_str("}\n");

    out
}